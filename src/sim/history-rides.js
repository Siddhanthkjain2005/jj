function historicCar(year, name, profile) {
  const { variant, body, layout, cylinders, tyres, transmission, widths, focus, reference, source, tech, paint, ...physical } = profile;
  const id = `hist_${year}${variant ? `_${variant}` : ''}`;
  return {
    ...CAR_VX1,
    ...physical,
    id,
    name,
    summary: focus,
    bodyStyle: body,
    tire: { ...CAR_VX1.tire, ...physical.tire },
    susp: { ...CAR_VX1.susp, ...physical.susp },
    gearbox: { ...CAR_VX1.gearbox, ...physical.gearbox },
    liveries: [{ id: `archive_${id}`, name: 'Archive livery', primary: paint[0], secondary: paint[1], accent: paint[2] }],
    provenance: {
      mass: 'T', geometry: 'F', inertia: 'E', wheels: 'T', steering: 'T', suspension: 'T',
      tirePeak: 'T', tireShape: 'T', relaxation: 'T', rollingResistance: 'T', lowSpeedDamping: 'T',
      engine: 'T', gearing: 'T', drivetrainLoss: 'E', diff: 'T', brakes: 'T', aero: 'T',
    },
    history: {
      year, body, layout, cylinders, tyres, transmission, focus, tech,
      historicalReference: reference,
      source,
      wheelWidthFront: widths[0],
      wheelWidthRear: widths[1],
    },
  };
}

